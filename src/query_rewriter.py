"""query_rewriter.py — агент, переформулирующий вопрос пользователя в чистый,
поисково-пригодный вид ДО того, как основной агент начнёт работать.

Зачем отдельный агент, а не "основной агент сам разберётся": реальные
вопросы пользователей — опечатки, разговорные сокращения, неполные
предложения. RAG-поиск (эмбеддинги + BM25) чувствителен к формулировке:
чёткий вопрос ищется заметно точнее, чем сырой. Вынесение этого в отдельный
шаг — стандартный приём в продакшн RAG (query rewriting / query expansion),
не выдумка ради количества агентов.

Важно: рерайтер НЕ должен трогать вопросы, где переформулировка не нужна
или опасна (например, арифметику) — иначе он может незаметно сломать
намерение вопроса ещё до того, как его увидит основной агент.
"""
from groq import Groq

from . import config

_client = None


def _get_client() -> Groq:
    global _client
    if _client is None:
        _client = Groq(api_key=config.GROQ_API_KEY)
    return _client


REWRITER_SYSTEM_PROMPT = (
    "Перепиши вопрос пользователя в чёткую, грамотную, САМОДОСТАТОЧНУЮ "
    "формулировку — исправь опечатки, разверни сокращения, убери "
    "двусмысленность. Если дан предыдущий контекст разговора и вопрос "
    "ссылается на него местоимением ('а что насчёт него?', 'а это?') — "
    "разверни ссылку явно, используя контекст, чтобы вопрос был понятен "
    "БЕЗ истории переписки. Если вопрос — математический пример или уже "
    "самодостаточен, верни его БЕЗ ИЗМЕНЕНИЙ. Не отвечай на вопрос, только "
    "переформулируй. Верни только текст вопроса, без пояснений и кавычек."
)


def rewrite(question: str, history: list[dict] = None) -> str:
    """history нужна для разрешения ссылок на предыдущие сообщения — без
    неё "а сколько там было?" непонятно, о чём вопрос вообще. Берём только
    последние несколько сообщений: для переформулировки текущего вопроса
    вся история диалога не нужна, важен только недавний контекст."""
    prompt = question
    if history:
        recent = "\n".join(f"{m['role']}: {m['content']}" for m in history[-4:])
        prompt = f"Предыдущий контекст разговора:\n{recent}\n\nВопрос: {question}"

    resp = _get_client().chat.completions.create(
        model=config.LLM_MODEL,
        messages=[
            {"role": "system", "content": REWRITER_SYSTEM_PROMPT},
            {"role": "user", "content": prompt},
        ],
        temperature=0,
    )
    return resp.choices[0].message.content.strip()
